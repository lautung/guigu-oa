CREATE TABLE IF NOT EXISTS sys_user (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(20),
  password VARCHAR(100),
  name VARCHAR(20),
  phone VARCHAR(20),
  head_url VARCHAR(200),
  dept_id BIGINT,
  description VARCHAR(255),
  open_id VARCHAR(100),
  status TINYINT DEFAULT 1,
  create_time TIMESTAMP,
  update_time TIMESTAMP,
  is_deleted TINYINT NOT NULL DEFAULT 0,
  token_version BIGINT NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_user_username ON sys_user (username);

CREATE TABLE IF NOT EXISTS sys_menu (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id BIGINT DEFAULT 0,
  name VARCHAR(50),
  type TINYINT,
  path VARCHAR(200),
  component VARCHAR(200),
  perms VARCHAR(100),
  icon VARCHAR(100),
  sort_value INT,
  status TINYINT DEFAULT 1,
  create_time TIMESTAMP,
  update_time TIMESTAMP,
  is_deleted TINYINT NOT NULL DEFAULT 0
);

-- 授予闭包（/info 与 backofficeGate）要 join 这三张表；注册合同测试用它们证明
-- 新用户零角色时看不到任何后台页面。
CREATE TABLE IF NOT EXISTS sys_role (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_name VARCHAR(100),
  role_code VARCHAR(100),
  description VARCHAR(255),
  data_scope TINYINT,
  create_time TIMESTAMP,
  update_time TIMESTAMP,
  is_deleted TINYINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS sys_user_role (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT,
  role_id BIGINT,
  create_time TIMESTAMP,
  update_time TIMESTAMP,
  is_deleted TINYINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS sys_role_menu (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_id BIGINT,
  menu_id BIGINT,
  create_time TIMESTAMP,
  update_time TIMESTAMP,
  is_deleted TINYINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS sys_config (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  config_key VARCHAR(100) NOT NULL,
  config_value VARCHAR(500),
  config_name VARCHAR(100) NOT NULL,
  value_type VARCHAR(20) NOT NULL DEFAULT 'string',
  builtin TINYINT NOT NULL DEFAULT 0,
  remark VARCHAR(500),
  create_time TIMESTAMP,
  update_time TIMESTAMP,
  is_deleted TINYINT NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_config_key ON sys_config (config_key);

CREATE TABLE IF NOT EXISTS sys_login_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(64),
  user_id BIGINT,
  dept_id BIGINT,
  ip VARCHAR(45),
  browser VARCHAR(50),
  os VARCHAR(50),
  status TINYINT NOT NULL DEFAULT 0,
  msg VARCHAR(500),
  event VARCHAR(20) NOT NULL DEFAULT 'login',
  create_time TIMESTAMP
);

