-- 业务审批桩域的测试表（#289 合同测试专用）：桩回调把自己的「单据状态」落第一张表、
-- 每次回调落一行第二张表。回调日志行的存在性是「回调与审批动作同事务」的证据：
-- 异值抛错回滚后日志行必须不存在（若回调在独立事务里提交，它会在动作回滚后存活）。
CREATE TABLE IF NOT EXISTS business_approval_stub_doc (
  business_id BIGINT PRIMARY KEY,
  status VARCHAR(20),
  update_time TIMESTAMP
);

CREATE TABLE IF NOT EXISTS business_approval_stub_callback_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id BIGINT NOT NULL,
  outcome VARCHAR(20) NOT NULL,
  in_transaction VARCHAR(5)
);

