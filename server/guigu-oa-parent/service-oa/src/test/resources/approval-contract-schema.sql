CREATE TABLE IF NOT EXISTS oa_process_type (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(50),
  description VARCHAR(255),
  create_time TIMESTAMP,
  update_time TIMESTAMP,
  is_deleted TINYINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS oa_process_template (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(50),
  icon_url VARCHAR(200),
  process_type_id BIGINT,
  form_props CLOB,
  form_options CLOB,
  description VARCHAR(255),
  process_definition_key VARCHAR(100),
  process_definition_path VARCHAR(200),
  process_model_id VARCHAR(100),
  status TINYINT DEFAULT 0,
  create_time TIMESTAMP,
  update_time TIMESTAMP,
  is_deleted TINYINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS oa_process (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  process_code VARCHAR(50),
  user_id BIGINT,
  process_template_id BIGINT,
  process_type_id BIGINT,
  title VARCHAR(200),
  description VARCHAR(255),
  form_values CLOB,
  process_instance_id VARCHAR(100),
  current_auditor VARCHAR(200),
  status TINYINT DEFAULT 0,
  create_time TIMESTAMP,
  update_time TIMESTAMP,
  is_deleted TINYINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS oa_process_record (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  process_id BIGINT,
  description VARCHAR(255),
  status TINYINT,
  operate_user_id BIGINT,
  operate_user VARCHAR(200),
  create_time TIMESTAMP,
  update_time TIMESTAMP,
  is_deleted TINYINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS oa_attachment (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  process_id BIGINT,
  owner_user_id BIGINT NOT NULL,
  draft_id VARCHAR(36),
  storage_id VARCHAR(36) NOT NULL,
  object_key VARCHAR(512) NOT NULL,
  temporary_object_key VARCHAR(512),
  file_name VARCHAR(255) NOT NULL,
  content_type VARCHAR(255) NOT NULL,
  size_bytes BIGINT NOT NULL,
  status VARCHAR(16) NOT NULL,
  upload_expires_at TIMESTAMP,
  create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  update_time TIMESTAMP,
  is_deleted TINYINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS sys_role_menu (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_id BIGINT,
  menu_id BIGINT,
  create_time TIMESTAMP,
  update_time TIMESTAMP,
  is_deleted TINYINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS sys_user_role (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_id BIGINT,
  user_id BIGINT,
  create_time TIMESTAMP,
  update_time TIMESTAMP,
  is_deleted TINYINT NOT NULL DEFAULT 0
);

